let LANG = (() => {
  try { const s = JSON.parse(localStorage.getItem('gtmeet.settings') || '{}'); if (s.lang && LANGS.some(l => l.code === s.lang)) return s.lang; } catch {}
  const n = (navigator.language || 'ko').toLowerCase();
  return n.startsWith('ko') ? 'ko' : n.startsWith('ja') ? 'ja' : n.startsWith('zh') ? 'zh' : n.startsWith('en') ? 'en' : 'en';
})();
let LANG_INFO, LOCALE, LIDX;
function setLangVars(code) {
  LANG = code; LANG_INFO = LANGS.find(l => l.code === code) || LANGS[0]; LOCALE = LANG_INFO.locale;
  LIDX = { en: 0, ja: 1, zh: 2 }[code]; document.documentElement.lang = code;
}
setLangVars(LANG);

function T(key, params) {
  let s = key;
  if (LIDX !== undefined) {
    const e = D[key] || D[String(key).trim()];
    if (e && e[LIDX]) s = e[LIDX];
    else if (typeof key === 'string') { // 서버 메시지처럼 뒤에 세부 내용이 붙은 경우: 알려진 앞부분만 번역
      const pre = Object.keys(D).filter(k => k.length > 6 && key.startsWith(k)).sort((a, b) => b.length - a.length)[0];
      if (pre) s = D[pre][LIDX] + key.slice(pre.length);
    }
  }
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => params[k] ?? m);
  return s;
}

// HTML 고정 문구 번역 (원문을 기억해 두므로 언어를 바꿔도 다시 적용 가능)
const _orig = new WeakMap();
function applyI18n(root = document.body) {
  document.title = T('GT-Meet 화상회의');
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: n => /[가-힣]/.test(_orig.get(n) ?? n.nodeValue) && !n.parentElement.closest('script,style,textarea,.no-i18n') ? 1 : 3 });
  const nodes = []; while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    if (!_orig.has(n)) _orig.set(n, n.nodeValue);
    const o = _orig.get(n), lead = o.match(/^\s*/)[0], trail = o.match(/\s*$/)[0];
    n.nodeValue = lead + T(o.trim()) + trail;
  }
  root.querySelectorAll('[placeholder],[title],[aria-label]').forEach(e => {
    for (const a of ['placeholder', 'title', 'aria-label']) {
      if (!e.hasAttribute(a)) continue;
      const key = 'i18n' + a.replace('-', '');
      if (!e.dataset[key]) { if (!/[가-힣]/.test(e.getAttribute(a))) continue; e.dataset[key] = e.getAttribute(a); }
      e.setAttribute(a, T(e.dataset[key]));
    }
  });
}
